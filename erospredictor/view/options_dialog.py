"""Keep occasional controls out of the draft's main decision flow."""

from PyQt6.QtWidgets import QDialog, QDialogButtonBox, QFormLayout, QLabel, QTabWidget, QVBoxLayout, QWidget


class OptionsDialog(QDialog):
    def __init__(self, window):
        super().__init__(window)
        self.setWindowTitle("Beállítások és előzmények")
        self.resize(650, 420)
        layout = QVBoxLayout(self)
        tabs = QTabWidget()
        layout.addWidget(tabs)
        recommendation = QWidget()
        rec = QVBoxLayout(recommendation)
        rec.addWidget(window.chk_meta)
        rec.addWidget(window.chk_effects)
        rec.addWidget(window.chk_robust)
        note = QLabel("A több kiosztásos elemzés az első öt jelöltet legfeljebb három ellenfél-felállásban vizsgálja, és a legrosszabb vizsgált becslés alapján rendezi át őket. A kijelzett fő százalék az aktuális draft becslése marad.")
        note.setWordWrap(True)
        rec.addWidget(note)
        rec.addStretch()
        tabs.addTab(recommendation, "Ajánlás és elemzés")
        client = QWidget()
        form = QFormLayout(client)
        form.addRow("Saját oldal, ha a kliens nem közli:", window.cb_sync_side)
        form.addRow(window.btn_lockfile)
        client_note = QLabel("A draftkövetés a főablak Automatikus draft kapcsolójával indul. Draft normal, Ranked Solo/Duo és Ranked Flex esetén ugyanazt a helyi hősválasztási végpontot használja. A custom botok választásait a kliens nem mindig közli.")
        client_note.setWordWrap(True)
        form.addRow(client_note)
        tabs.addTab(client, "LoL-kliens")
        history = QWidget()
        history_layout = QVBoxLayout(history)
        history_layout.addWidget(window.chk_personal)
        window.lbl_history.setMaximumWidth(580)
        history_layout.addWidget(window.lbl_history)
        history_layout.addWidget(window.cb_history_limit)
        history_layout.addWidget(window.btn_history)
        history_layout.addWidget(window.chk_history_service)
        history_note = QLabel("A személyes előzményjelölés és a kézzel szerkesztett hőspool külön is használható. A külső Riot-előzményopció alapból kikapcsolt; használatához külön frissítés szükséges.")
        history_note.setWordWrap(True)
        history_layout.addWidget(history_note)
        history_layout.addStretch()
        tabs.addTab(history, "Saját előzmények")
        self.preferences_notice = QLabel()
        self.preferences_notice.setWordWrap(True)
        self.preferences_notice.setStyleSheet("color: #EF9A9A;")
        self.preferences_notice.hide()
        layout.addWidget(self.preferences_notice)
        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        buttons.button(QDialogButtonBox.StandardButton.Close).setText("Bezárás")
        buttons.rejected.connect(self.close)
        layout.addWidget(buttons)
